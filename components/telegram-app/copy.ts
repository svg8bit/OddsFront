export function localizeError(copy: MiniAppCopy, message: string) {
  if (copy.lang !== "ru" || !message) return message;
  for (const [pattern, russian] of RU_ERRORS) {
    const match = message.match(pattern);
    if (match) return typeof russian === "string" ? russian : russian(match);
  }
  return message;
}

export function miniAppCopy(languageCode: string | undefined): MiniAppCopy {
  return /^(ru|uk|be|kk|uz|ky|tg|hy|az)/i.test(languageCode || "en") ? ru : en;
}
